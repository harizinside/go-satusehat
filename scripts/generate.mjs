function pascal(name) {
  return name
    .replace(/-/g, "_")
    .split("_")
    .filter((w) => w.length > 0)
    .map((w) => (INITIALISMS.has(w.toUpperCase()) ? w.toUpperCase() : w[0].toUpperCase() + w.slice(1)))
    .join("");
}

// Walk AST and return a list of: { kind, decl, jsdoc }
// where kind ∈ 'interface' | 'function' | 'reExport' | 'var'.
function parseFile(text, fileName) {
  const sf = ts.createSourceFile(fileName, text, ts.ScriptTarget.Latest, true);
  const out = [];
  for (const stmt of sf.statements) {
    const jsdoc = ts.getJSDocCommentsAndTags(stmt).map((d) =>
      d.getText().replace(/^\/\*\*|\*\/$/g, "").split("\n").map((l) => l.replace(/^\s*\* ?/, "")).join("\n").trim()
    ).join("\n");

    if (ts.isInterfaceDeclaration(stmt)) {
      out.push({ kind: "interface", name: stmt.name.text, decl: stmt, jsdoc });
    } else if (ts.isFunctionDeclaration(stmt) && hasExportModifier(stmt)) {
      out.push({ kind: "function", name: stmt.name?.text || "(anon)", decl: stmt, jsdoc });
    } else if (ts.isExportDeclaration(stmt)) {
      if (stmt.exportClause && ts.isNamedExports(stmt.exportClause)) {
        const reExports = stmt.exportClause.elements.map((e) => e.name.text);
        const module = stmt.moduleSpecifier?.text || "";
        out.push({ kind: "reExport", names: reExports, module, jsdoc });
      }
    } else if (ts.isVariableStatement(stmt) && hasExportModifier(stmt)) {
      // const xxx = ... (rare; ignore).
    }
  }
  return out;
}

function hasExportModifier(node) {
  const mods = ts.canHaveModifiers(node) ? ts.getModifiers(node) : undefined;
  return !!mods?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword);
}

// — TS type → Go type ————————————————————————————————————————————————————

function tsTypeToGo(typeNode, declaredOptional) {
  if (!typeNode) return { go: "any", optional: declaredOptional ?? false };
  return convertType(typeNode, declaredOptional ?? false);
}

function convertType(typeNode, parentOptional) {
  if (ts.isTypeReferenceNode(typeNode)) {
    const args = typeNode.typeArguments;
    const name = typeNode.typeName.text;
    // Array<X> → []X
    if (name === "Array" && args && args.length === 1) {
      const inner = convertType(args[0], false);
      return { go: "[]" + inner.go, optional: parentOptional };
    }
    // Record<string, X> → map[string]X
    if (name === "Record" && args && args.length === 2) {
      const key = args[0];
      const val = convertType(args[1], false);
      const keyGo = key.kind === ts.SyntaxKind.StringKeyword ? "string" : (key.text || "string");
      return { go: `map[${keyGo}]${val.go}`, optional: parentOptional };
    }
    // FhirPatchOperation[] → []PatchOp
    if (name === "FhirPatchOperation") return { go: "core.PatchOp", optional: parentOptional };
    if (name === "FhirBundle") return { go: "core.Bundle", optional: parentOptional };
    if (name === "FhirResource") return { go: "core.Resource", optional: parentOptional };
    // Other named types → assume they're generated alongside in the same package.
    return { go: goName(name), optional: parentOptional };
  }
  if (typeNode.kind === ts.SyntaxKind.StringKeyword) return { go: "string", optional: parentOptional };
  if (typeNode.kind === ts.SyntaxKind.NumberKeyword) return { go: "float64", optional: parentOptional };
  if (typeNode.kind === ts.SyntaxKind.BooleanKeyword) return { go: "bool", optional: parentOptional };
  if (typeNode.kind === ts.SyntaxKind.AnyKeyword || typeNode.kind === ts.SyntaxKind.UnknownKeyword) return { go: "any", optional: parentOptional };
  if (ts.isUnionTypeNode(typeNode)) {
    // X | Y | null → first concrete type. For string|number etc., fall back to any.
    const nonNull = typeNode.types.filter((t) => t.kind !== ts.SyntaxKind.NullLiteral && t.kind !== ts.SyntaxKind.UndefinedKeyword);
    if (nonNull.length === 1) return convertType(nonNull[0], parentOptional);
    return { go: "any", optional: parentOptional };
  }
  if (ts.isLiteralTypeNode(typeNode)) {
    return { go: "string", optional: parentOptional };
  }
  if (ts.isArrayTypeNode(typeNode)) {
    const inner = convertType(typeNode.elementType, false);
    return { go: "[]" + inner.go, optional: parentOptional };
  }
  if (ts.isParenthesizedTypeNode(typeNode)) {
    return convertType(typeNode.type, parentOptional);
  }
  // Inline object type → anonymous struct.
  if (ts.isTypeLiteralNode(typeNode)) {
    return { go: anonymousStruct(typeNode), optional: parentOptional };
  }
  return { go: "any", optional: parentOptional };
}

// Request-body field: unset must never serialize as `{}`, `null`, `false` or
// `0` (FHIR rejects empty objects and mutually exclusive choice[x] siblings).
// Structs stay values (so `body.Subject.Reference = ...` works) with
// `omitzero`; bools/numbers become pointers so an explicit false/0 survives.
function field(go, jsonName) {
  if (go === "bool" || go === "float64") return { go: "*" + go, tag: `\`json:"${jsonName},omitempty"\`` };
  const isStruct = go.startsWith("struct {") || (/^(core\.)?[A-Z]\w*$/.test(go) && go !== "core.Resource");
  return { go, tag: `\`json:"${jsonName},${isStruct ? "omitzero" : "omitempty"}"\`` };
}

function anonymousStruct(literal) {
  const fields = [];
  let hasIndex = false;
  let indexKey = "string";
  let indexVal = "any";
  for (const m of literal.members) {
    if (ts.isIndexSignatureDeclaration(m)) {
      hasIndex = true;
      const param = m.parameters[0];
      indexKey = param?.type?.kind === ts.SyntaxKind.NumberKeyword ? "int" : "string";
      indexVal = convertType(m.type, false).go;
      continue;
    }
    if (!ts.isPropertySignature(m)) continue;
    const fname = m.name.text || (m.name.escapedText?.toString() ?? "");
    const t = convertType(m.type, !!m.questionToken);
    const f = field(t.go, fname);
    fields.push(`\t${goName(fname)} ${f.go} ${f.tag}`);
  }
  if (hasIndex) {
    fields.push(`\tExtra map[${indexKey}]${indexVal} \`json:"-"\``);
  }
  return `struct {\n${fields.join("\n")}\n}`;
}

