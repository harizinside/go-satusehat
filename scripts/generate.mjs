// Tracks names seen so far across all files to detect collisions and prefix
// duplicates with the module basename.
const globalNames = new Map();
const nameRemap = new Map(); // originalName (uppercase TS) → renamed Go name (used by method bodies)
function uniqueName(name, file, nsName) {
  const seen = globalNames.get(name) || [];
  if (!seen.length) {
    globalNames.set(name, [file]);
    return name;
  }
  if (seen.includes(file) && !nsName) return nameRemap.get(name) || name;
  if (seen.includes(file) && nsName && seen[0] === nsName) return nameRemap.get(name) || name;
  const pfx = pascal(file).replace(/Service$/, "");
  const renamed = pfx + name;
  if (!globalNames.has(renamed)) globalNames.set(renamed, [file]);
  seen.push(file);
  globalNames.set(name, seen);
  nameRemap.set(name, renamed);
  return renamed;
}

function interfaceToGo(iface, nameHint, fileBase, nsName) {
  const orig = nameHint || iface.name;
  const name = uniqueName(orig, fileBase, nsName);
  let fields = [];
  let hasIndexSignature = false;
  let indexKey = "string";
  let indexVal = "any";
  for (const m of iface.decl.members) {
    if (ts.isIndexSignatureDeclaration(m)) {
      hasIndexSignature = true;
      const param = m.parameters[0];
      indexKey = param?.type?.kind === ts.SyntaxKind.NumberKeyword ? "int" : "string";
      indexVal = convertType(m.type, false).go;
      continue;
    }
    if (!ts.isPropertySignature(m)) continue;
    const fname = m.name.text || (m.name.escapedText?.toString() ?? "");
    const safeFName = fname.replace(/-/g, "_");
    const t = convertType(m.type, !!m.questionToken);
    // Drop leading underscore for the Go field name (Go would treat it as
    // unexported, which would clash with JSON unmarshalling).
    const goFieldName = goName(fname).replace(/^_/, "");
    fields.push({ name: goFieldName, ...field(t.go, safeFName) });
  }
  if (fields.length === 0 && !hasIndexSignature) {
    // Empty interface → anonymous struct with Extra.
    fields.push({ name: "Extra", go: "map[string]any", tag: '`json:"-"`' });
    return { name, fields, hasIndexSignature: true, indexKey, indexVal, hasExtra: true };
  }
  if (hasIndexSignature) {
    fields.push({ name: "Extra", go: `map[${indexKey}]${indexVal}`, tag: '`json:"-"`' });
  }
  // Build a per-field map of original TS name → Go name so the generator can
  // find the right struct field from a query key (the TS source uses
  // `_include` as both the interface field name AND the URL query key).
  const fieldByOriginal = new Map();
  for (const m of iface.decl.members) {
    if (!ts.isPropertySignature(m)) continue;
    const fname = m.name.text || m.name.escapedText?.toString() || "";
    fieldByOriginal.set(fname, goName(fname).replace(/^_/, ""));
  }
  return { name, fields, hasIndexSignature, indexKey, indexVal, hasExtra: hasIndexSignature, fieldByOriginal };
}

