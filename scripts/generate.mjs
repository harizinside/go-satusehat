// Walk `client.request(method, path, options)` to find HTTP verb, path, and
// whether `body` or `query` was passed. Returns { method, pathTemplate,
// pathArgs, queryKeys, bodyIsOperations, responseType }.
function extractRequestInfo(fn) {
  let method = "GET", pathTemplate = "", bodyIsOperations = false;
  let queryKeys = [];
  let pathArgs = [];
  let responseType = "any";

  // Find the return type from the function declaration's type.
  const ret = fn.type?.typeArguments?.[0];
  if (ret) {
    responseType = mapReturnType(ret);
  }

  const visit = (node) => {
    if (ts.isCallExpression(node) &&
        ts.isPropertyAccessExpression(node.expression) &&
        node.expression.expression.text === "client" &&
        node.expression.name.text === "request") {
      const args = node.arguments;
      if (args.length >= 2) {
        // method = string literal at args[0]
        method = args[0].text || args[0].getText().replace(/^["']|["']$/g, "");
      }
      if (args.length >= 2) {
        const pathArg = args[1];
        if (ts.isTemplateExpression(pathArg)) {
          pathTemplate = pathArg.head.text;
          for (const span of pathArg.templateSpans) {
            pathArgs.push(extractPathArg(span.expression));
            pathTemplate += "${...}" + span.literal.text;
          }
        } else if (ts.isNoSubstitutionTemplateLiteral(pathArg)) {
          pathTemplate = pathArg.text;
        } else if (ts.isStringLiteral(pathArg)) {
          pathTemplate = pathArg.text;
        } else if (pathArg.getText) {
          const raw = pathArg.getText().replace(/^["'`]|[`'"]$/g, "");
          if (raw.startsWith("/")) pathTemplate = raw;
        }
      }
      if (args.length >= 3 && ts.isObjectLiteralExpression(args[2])) {
        for (const prop of args[2].properties) {
          if (ts.isPropertyAssignment(prop)) {
            const name = prop.name.text || prop.name.escapedText?.toString();
            if (name === "body") {
              if (prop.initializer.text === "operations") bodyIsOperations = true;
            }
            if (name === "query" && ts.isObjectLiteralExpression(prop.initializer)) {
              for (const q of prop.initializer.properties) {
                if (ts.isPropertyAssignment(q)) {
                  const key = q.name.text || q.name.escapedText?.toString();
                  // The TS source maps `params.<srcField>` to the URL query
                  // key `<key>` (sometimes different, e.g. `_include` ←→ `include`).
                  const srcField = ts.isIdentifier(q.initializer) || ts.isPropertyAccessExpression(q.initializer)
                    ? q.initializer.text || (q.initializer.name?.text ?? "")
                    : "";
                  queryKeys.push({ queryKey: key, fieldName: srcField.replace(/^params\./, "") });
                }
              }
            }
          }
        }
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(fn.body);
  return { method, pathTemplate, pathArgs, queryKeys, bodyIsOperations, responseType };
}


// Detect TS source expressions like `encodeURIComponent(id)` and turn them
// into a Go `url.PathEscape(id)` call.
function extractPathArg(expr) {
  if (ts.isIdentifier(expr)) return expr.text;
  if (ts.isCallExpression(expr) && ts.isIdentifier(expr.expression)) {
    if (expr.expression.text === "encodeURIComponent") {
      const arg = expr.arguments[0];
      return `url.PathEscape(${arg.text || arg.getText()})`;
    }
  }
  return expr.text || expr.getText();
}

function mapReturnType(t) {
  if (!t) return "any";
  if (ts.isTypeReferenceNode(t)) {
    const name = t.typeName.text;
    if (name === "FhirResource") {
      const arg = t.typeArguments?.[0];
      return "core.Resource";
    }
    if (name === "FhirBundle") return "*core.Bundle";
    return goName(name);
  }
  if (t.kind === ts.SyntaxKind.UnknownKeyword) return "any";
  if (t.kind === ts.SyntaxKind.VoidKeyword) return "";
  return "any";
}

// Given an interface, build the Go method signature + body.
function methodSignatureAndBody(fn, iface, ifaces, ns, responseType) {
  const params = fn.parameters.slice(1); // skip client
  const args = params.map((p) => ({ name: p.name.text, type: p.type ? convertType(p.type, !!p.questionToken) : { go: "any", optional: false } }));
  const remap = (n) => nameRemap.get(n) || n;
  let interfaceName = args.find((a) => a.name === "body" || a.name === "operations")?.type.go;
  interfaceName = interfaceName ? remap(interfaceName) : undefined;
  let paramsName = args.find((a) => a.name === "params")?.type.go;
  paramsName = paramsName ? remap(paramsName) : undefined;
  // Last positional arg is the Go method name; keep camelCase for a struct
  // field name on `Client.RawatJalan.Anamnesis` mapping: `ConditionKeluhanUtama`.

  // Path args.
  const pathArgs = extractRequestInfo(fn);
  const pathExpr = buildPathExpr(pathArgs);

  // Build the method.
  const ctx = "ctx context.Context";
  const inArgs = [];
  inArgs.push(ctx);
  for (const a of args) {
    if (a.name === "operations") {
      inArgs.push(`operations []core.PatchOp`);
    } else if (a.name === "body") {
      const t = interfaceName || "any";
      inArgs.push(`body ${t}`);
    } else if (a.name === "params") {
      const t = paramsName || "any";
      inArgs.push(`params ${t}`);
    } else {
      // path arg (id, claimId, claimId2, etc.)
      inArgs.push(`${a.name} string`);
    }
  }

  // Body of the method.
  const lines = [];
  const call = `s.c.Request${ns.maybeMasterData ? "MasterData" : ""}(ctx, ${q(pathArgs.method)}, ${buildPathExpr(pathArgs)}, ${buildOpts(pathArgs, args)})`;
  const wrap = { "core.Resource": "core.AsResource", "*core.Bundle": "core.AsBundle" }[responseType];
  lines.push(`func (s *${ns.serviceName}) ${goName(fn.name.text)}(${inArgs.join(", ")}) (${wrap ? responseType : "any"}, error) {`);
  lines.push(`\treturn ${wrap ? `${wrap}(${call})` : call}`);
  lines.push(`}`);
  return { code: lines.join("\n"), method: pathArgs.method, pathArgs };
}

function buildPathExpr(pathArgs) {
  const t = pathArgs.pathTemplate || "";
  const pathArgsList = pathArgs.pathArgs;
  if (!t && !pathArgsList.length) return q("/");
  if (!pathArgsList.length) return q("/" + t.replace(/^\/+/, ""));
  // Split the template at the substitution markers and produce a Go string
  // concat: "/Observation/" + id + "/foo" + bar.
  const segments = t.split(/\$\{\.\.\.\}/);
  if (segments.length !== pathArgsList.length + 1) {
    // Fallback: fmt.Sprintf with %s placeholders.
    let format = t.replace(/\$\{\.\.\.\}/g, "%s");
    return `fmt.Sprintf(${q("/" + format.replace(/^\/+/, ""))}${pathArgsList.map((a) => ", " + (a.startsWith("url.PathEscape(") ? a : `url.PathEscape(${a})`)).join("")})`;
  }
  let pieces = [q("/" + segments[0].replace(/^\/+/, ""))];
  for (let i = 0; i < pathArgsList.length; i++) {
    const a = pathArgsList[i];
    pieces.push(` + ${a.startsWith("url.PathEscape(") ? a : `url.PathEscape(${a})`}`);
    if (segments[i + 1]) pieces.push(` + ${q(segments[i + 1])}`);
  }
  return pieces.join("");
}

function buildOpts(pathArgs, args) {
  const opts = [];
  if (pathArgs.queryKeys.length) {
    const qparts = pathArgs.queryKeys.map(({ queryKey, fieldName }) => {
      const safeKey = queryKey.replace(/-/g, "_");
      const srcField = fieldName || queryKey;
      const goField = goName(srcField.replace(/-/g, "_")).replace(/^_/, "");
      return `"${safeKey}": params.${goField}`;
    });
    opts.push(`Query: map[string]any{${qparts.join(", ")}}`);
  }
  if (pathArgs.bodyIsOperations) {
    opts.push("Body: operations");
  } else if (args.find((a) => a.name === "body")) {
    opts.push("Body: body");
  }
  if (!opts.length) return "nil";
  return `&core.RequestOptions{${opts.join(", ")}}`;
}

// — main loop ————————————————————————————————————————————————————————————

const nsPlan = []; // { name, fields: [{ name, typeName, file }] }
const generatedServiceCount = { total: 0 };

for (const group of GROUPS) {
  const dir = join(nodeRepo, "src", group.dir);
  let files;
  try {
    files = readdirSync(dir).filter((f) => f.endsWith(".ts") && !group.skip.has(f));
  } catch (e) {
    console.warn(`skip ${group.dir}: ${e.message}`);
    continue;
  }
  // Each group is its own Go package, so type names only need to be unique
  // within the group.
  globalNames.clear();
  nameRemap.clear();
  const pkg = group.ns.toLowerCase(); // FHIR → fhir, RawatJalan → rawatjalan, ...
  const pkgDir = join(outRoot, pkg);
  // Drop this generator's previous output so deleted TS modules don't linger.
  if (existsSync(pkgDir)) {
    for (const f of readdirSync(pkgDir)) {
      const p = join(pkgDir, f);
      if (f.endsWith(".go") && readFileSync(p, "utf8").startsWith(GENERATED_HEADER)) rmSync(p);
    }
  }
  for (const file of files) {
    const text = readFileSync(join(dir, file), "utf8");
    const stmts = parseFile(text, file);
    if (!stmts.length) continue;

    const fileBase = fileBaseName(file);
    // Service name: file basename within the group's package, e.g.
    // fhir.AccountService, rawatjalan.AnamnesisService.
    const serviceName = pascal(fileBase) + "Service";
    const fieldName = pascal(fileBase);

    const interfaces = stmts.filter((s) => s.kind === "interface");
    const functions = stmts.filter((s) => s.kind === "function");
    const reExports = stmts.find((s) => s.kind === "reExport");

    // If file has no functions and only re-exports, skip generating a service.
    // (The re-exports are wired into the namespace as separate delegates.)
    if (!functions.length && reExports) {
      for (const name of reExports.names) {
        const delegate = DELEGATE[name];
        if (!delegate) continue;
        nsPlan.push({ ns: group.ns, field: fileBase, typeName: pascal(fileBase) + "Service", method: name, delegate });
      }
      continue;
    }
    if (!functions.length) continue;

    // Build file.
    const lines = [];
    lines.push(GENERATED_HEADER);
    lines.push("");
    lines.push(`package ${pkg}`);
    lines.push("");
    lines.push(`import "context"`);
    lines.push(`import "github.com/harizinside/go-satusehat/internal/core"`);
    lines.push("");
    if (interfaces.length) {
      for (const i of interfaces) {
        const go = interfaceToGo(i, i.name, fileBase, group.ns);
        if (go.jsdoc ?? false) lines.push(`// ${go.name}: ...`);
        const fieldLines = go.fields.map((f) => `\t${f.name} ${f.go} ${f.tag}`).join("\n");
        lines.push(`type ${go.name} struct {\n${fieldLines}\n}`);
        if (go.hasExtra) {
          lines.push(``);
          lines.push(`// MarshalJSON merges Extra into the top-level object.`);
          lines.push(`func (v ${go.name}) MarshalJSON() ([]byte, error) {`);
          lines.push(`\ttype plain ${go.name}`);
          lines.push(`\treturn core.MarshalWithExtra(plain(v), v.Extra)`);
          lines.push(`}`);
        }
        lines.push("");
      }
    }

    // Service struct.
    lines.push(`// ${serviceName} wraps ${fileBase} endpoints.`);
    lines.push(`type ${serviceName} struct {\n\tc core.Requester\n}`);
    lines.push("");

    // Methods.
    const ifaceMap = new Map(interfaces.map((i) => [i.name, i]));
    let usesNetURL = false;
    for (const f of functions) {
      const sig = methodSignatureAndBody(f.decl, null, ifaceMap, { serviceName, maybeMasterData: group.dir === "master-data" }, mapReturnType(f.decl.type?.typeArguments?.[0]));
      if (sig.code.includes("url.PathEscape")) usesNetURL = true;
      // Get JSDoc comment for the function.
      const jsdoc = (f.jsdoc || "").trim();
      if (jsdoc) {
        for (const line of jsdoc.split("\n")) lines.push(`// ${line}`);
      }
      lines.push(sig.code);
      lines.push("");
      generatedServiceCount.total += 1;
    }

    // Add "net/url" import if any method uses url.PathEscape.
    if (usesNetURL) {
      // Insert right after the existing "import context" line.
      const idx = lines.findIndex((l) => l.startsWith('import "'));
      if (idx >= 0) lines.splice(idx + 1, 0, 'import "net/url"');
    }

    if (!existsSync(pkgDir)) mkdirSync(pkgDir);
    writeFileSync(join(pkgDir, `${fileBase.replace(/-/g, "_")}.go`), lines.join("\n"));
    nsPlan.push({ ns: group.ns, pkg, field: fieldName, typeName: serviceName });
  }
}

// — namespaces —————————————————————————————————————————————————————————————
// Each group package gets namespace.go (its `Namespace` struct + `New`); the
// root gets zz_namespaces.go, which hangs every group off `*Client`.

// Group fields by namespace.
const fieldsByNs = new Map();
for (const f of nsPlan) {
  if (f.method) continue; // re-export delegates aren't surfaced as fields
  if (!fieldsByNs.has(f.ns)) fieldsByNs.set(f.ns, []);
  fieldsByNs.get(f.ns).push(f);
}

const MODULE = "github.com/harizinside/go-satusehat";

for (const [nsName, fields] of fieldsByNs) {
  const pkg = fields[0].pkg;
  const out = [GENERATED_HEADER, "", `package ${pkg}`, "", `import "${MODULE}/internal/core"`, ""];
  out.push(`// Namespace bundles the ${nsName} modules; it is reachable as c.${nsName} on a *satusehat.Client.`);
  out.push("type Namespace struct {");
  for (const f of fields) out.push(`\t${pascal(f.field)} *${f.typeName}`);
  out.push("}", "");
  out.push("// New wires every service onto r (normally a *satusehat.Client).");
  out.push("func New(r core.Requester) Namespace {");
  out.push("\treturn Namespace{");
  for (const f of fields) out.push(`\t\t${pascal(f.field)}: &${f.typeName}{c: r},`);
  out.push("\t}", "}", "");
  writeFileSync(join(outRoot, pkg, "namespace.go"), out.join("\n"));
}

const nsLines = [GENERATED_HEADER, "", "package satusehat", "", "import ("];
for (const [, fields] of fieldsByNs) nsLines.push(`\t"${MODULE}/${fields[0].pkg}"`);
nsLines.push(")", "");
nsLines.push("// GeneratedNamespaces holds every generated group;");
nsLines.push("// embedded in `Namespaces` so the top-level fields on `*Client` work.");
nsLines.push("type GeneratedNamespaces struct {");
for (const [nsName, fields] of fieldsByNs) nsLines.push(`\t${nsName} ${fields[0].pkg}.Namespace`);
nsLines.push("}", "");
nsLines.push("// buildGeneratedNamespaces wires per-group services onto a Client.");
nsLines.push("func buildGeneratedNamespaces(c *Client) *GeneratedNamespaces {");
nsLines.push("\treturn &GeneratedNamespaces{");
for (const [nsName, fields] of fieldsByNs) nsLines.push(`\t\t${nsName}: ${fields[0].pkg}.New(c),`);
nsLines.push("\t}", "}", "");

writeFileSync(join(outRoot, "zz_namespaces.go"), nsLines.join("\n"));

