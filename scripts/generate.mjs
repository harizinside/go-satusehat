function goName(key) {
  // Preserve leading underscore (FHIR uses "_id", "_include", etc.).
  let prefix = "";
  if (key.startsWith("_")) {
    prefix = "_";
    key = key.slice(1);
  }
  const isAllCaps = /^[A-Z0-9_]+$/.test(key);
  let parts;
  if (isAllCaps) {
    parts = key.split("_").filter(Boolean);
  } else {
    parts = key
      .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
      .replace(/([A-Z]+)([A-Z][a-z])/g, "$1 $2")
      .split(" ");
  }
  let out = "";
  for (const raw of parts) {
    let word;
    if (INITIALISMS.has(raw)) {
      word = raw;
    } else {
      word = raw[0].toUpperCase() + raw.slice(1).toLowerCase();
    }
    if (/[0-9]$/.test(out) && /^[0-9]/.test(word)) out += "_";
    out += word;
  }
  if (/^[0-9]/.test(out)) out = "C" + out;
  return prefix + out;
}

